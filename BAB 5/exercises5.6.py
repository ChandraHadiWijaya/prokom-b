age = 18
if age < 2:
    print("Orang tersebut adalah bayi .")
elif age < 4:
    print("Orang tersebut adalah balita .")
elif age < 13:
    print("Orang tersebut adalah anak-anak .")
elif age < 20:
    print("Orang tersebut adalah remaja .")
elif age < 65:
    print("Orang tersebut adalah orang dewasa .")
else:
    print("Orang tersebut adalah lansia .")
